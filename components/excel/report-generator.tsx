"use client"

import { useState } from "react"
import { Button } from "@/components/ui/button"
import { Loader2, Download } from "lucide-react"

interface ExcelData {
  id: string
  filename: string
  uploadTime: Date
  metadata: Record<string, any>
  data: Array<Record<string, any>>
  type: "metadata" | "scan-data" | "mixed"
}

interface ReportGeneratorProps {
  upload: ExcelData
}

export function ReportGenerator({ upload }: ReportGeneratorProps) {
  const [isGenerating, setIsGenerating] = useState(false)

  const generateReport = async () => {
    setIsGenerating(true)
    try {
      // Find anomalies in the data
      const thicknessValues = upload.data
        .map((row) => Object.values(row).find((v) => typeof v === "number"))
        .filter((v) => v !== undefined) as number[]

      const avgThickness = thicknessValues.reduce((a, b) => a + b, 0) / thicknessValues.length || 0
      const minThickness = Math.min(...thicknessValues)
      const maxThickness = Math.max(...thicknessValues)
      const anomalies = thicknessValues.filter((t) => t < avgThickness * 0.8).length

      // Create a simple text report
      const reportContent = `
SIGMA VISITANK - INSPECTION REPORT
===================================

File: ${upload.filename}
Date: ${upload.uploadTime.toLocaleString()}
Type: ${upload.type}

METADATA
--------
${Object.entries(upload.metadata)
  .map(([k, v]) => `${k}: ${v}`)
  .join("\n")}

DATA SUMMARY
------------
Total Measurements: ${upload.data.length}
Average Thickness: ${avgThickness.toFixed(2)} mm
Minimum Thickness: ${minThickness.toFixed(2)} mm
Maximum Thickness: ${maxThickness.toFixed(2)} mm

ANOMALIES DETECTED
------------------
${anomalies} measurements below 80% of average (${(avgThickness * 0.8).toFixed(2)} mm)

RECOMMENDATIONS
---------------
- Review areas with thickness below ${(avgThickness * 0.8).toFixed(2)} mm
- Schedule maintenance if corrosion rate is accelerating
- Consider protective coating in high-wear areas

Generated by Excel Data Analyzer
      `

      // Create a blob and download
      const blob = new Blob([reportContent], { type: "text/plain" })
      const url = window.URL.createObjectURL(blob)
      const a = document.createElement("a")
      a.href = url
      a.download = `report-${upload.filename.split(".")[0]}.txt`
      a.click()
      window.URL.revokeObjectURL(url)
    } finally {
      setIsGenerating(false)
    }
  }

  return (
    <Button onClick={generateReport} disabled={isGenerating} variant="default">
      {isGenerating ? (
        <>
          <Loader2 className="w-4 h-4 mr-2 animate-spin" />
          Generating...
        </>
      ) : (
        <>
          <Download className="w-4 h-4 mr-2" />
          Generate Report
        </>
      )}
    </Button>
  )
}
